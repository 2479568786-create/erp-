def category_title_guidance(category_name: str, product_name: str = "") -> tuple[str, str]:
    """返回稳定匹配的类目画像与标题结构建议。

    Ozon 同步的类目名为优先匹配输入；商品标题仅作为未匹配到类目时的兜底。
    """
    haystack = f"{category_name or ''} {product_name or ''}".casefold()
    for label, keywords, structure in _CATEGORY_TITLE_PROFILES:
        if any(keyword.casefold() in haystack for keyword in keywords):
            return label, structure
    return "通用商品", "核心品类词 + 型号/尺寸/容量 + 2—3 个真实功能卖点 + 使用场景/人群 + 兼容性或套装组成"